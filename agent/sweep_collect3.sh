#!/usr/bin/env bash
# 3차 스윕 (#180) — 미개척 축 세 개를 판다.
#
# 1·2차에서 확인된 것: 수율 최고 경로는 **공정위 사건명 '불공정약관조항'**이었다
# (통과 50행 중 38행). 그런데 그 축은 거의 소진됐다(사건명 검색 195건 중 180건 수집).
# 그래서 다른 축으로 옮긴다.
set -u
cd "$(dirname "$0")"
PY=./.venv/bin/python

run() { echo "### $1:$2"; $PY collect_cases.py --target "$1" --query "$2" --section "${3:-2}" --limit 40 2>&1 | grep -E "^조항 후보|판정 후보" || echo "  (수집 0)"; }

# ① 공정위 본문 검색 — 사건명에 '약관'이 없는 나머지 약 280건.
#    거래상지위남용·가맹사업 사건에도 조항 판단이 들어 있다.
for q in 불공정약관 시정명령약관 약관조항무효 거래상지위남용 가맹계약서; do run ftc "$q"; done

# ② 소비자 계약 유형별 판례 — 우리 골든셋에 없는 업종.
#    유형이 다르면 조항 문언도 달라서, 같은 위험 유형이라도 새 표현을 준다.
for q in 상조계약 예식장계약 학원수강료 렌터카계약 이사계약 결혼중개 \
         통신서비스약관 항공운송약관 숙박예약취소 헬스장이용계약 \
         골프회원권 콘도회원권 주차장약관 택배약관; do run prec "$q"; done

# ③ 나머지 target — 수량은 작지만 도메인이 다르다.
for t in decc ppc fsc acr; do run "$t" 약관; done
