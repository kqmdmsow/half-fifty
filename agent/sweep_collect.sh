#!/usr/bin/env bash
# 위험 유형 10종을 겨냥한 판례 수집 스윕 (#180).
# 조항 원문이 병목이므로 조항을 본문에 인용하는 판례를 주력으로 삼는다.
set -u
cd "$(dirname "$0")"
PY=./.venv/bin/python

# 유형별 질의. 한 유형에 여러 표현을 넣는 이유는 판결문이 쓰는 말이
# 우리 유형명과 다르기 때문이다.
QUERIES=(
  # 과도한 위약금
  위약금 손해배상예정 위약벌 해약금 계약금몰취
  # 일방적 계약 해지
  계약해지 해지권 기한이익상실 자동해지
  # 보증금 반환 지연
  보증금반환 임대차보증금 반환지연
  # 책임 면제
  면책조항 면책약관 손해배상책임제한
  # 불명확한 수수료·이자
  중도상환수수료 지연손해금 연체이자 수수료약정
  # 신탁관계
  담보신탁 수탁자책임 신탁부동산임대차
  # 부당한 비용 전가
  원상회복비용 관리비부담 비용부담약정
  # 일방적 급부·조건 변경
  약관변경 이용조건변경 요금변경
  # 선택권 제한·구입 강제
  전속계약 구입강제
  # 권리행사 제한
  전속관할합의 항변권포기 청약철회제한 제소전화해
)

for q in "${QUERIES[@]}"; do
  echo "### $q"
  $PY collect_cases.py --target prec --query "$q" --section 2 --limit 45 2>&1 \
    | grep -E "^조항 후보|판정 후보" || echo "  (수집 0)"
done
