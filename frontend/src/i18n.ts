/** 문서 유형 표시 라벨 (API 값은 한국어 그대로 전송). */
export function domainLabel(lang: LangCode, koreanDomain: string): string {
  if (lang === 'ko') return koreanDomain
  return DOMAIN_LABELS[lang]?.[koreanDomain] ?? DOMAIN_LABELS.en[koreanDomain] ?? koreanDomain
}

export function t(
  lang: LangCode,
  key: UIKey | ExtraKey | LandingKey | ScreenKey | SampleKey,
  vars?: Record<string, number | string>,
): string {
  const lookup = (dicts: Array<Record<string, Record<string, string>>>, code: LangCode) => {
    for (const dict of dicts) {
      const value = dict[code]?.[key]
      if (value !== undefined) return value
    }
    return undefined
  }
  const dicts = [UI, UI_EXTRA, UI_LANDING, UI_SCREENS, UI_SAMPLES] as Array<Record<string, Record<string, string>>>
  let text = lookup(dicts, lang) ?? lookup(dicts, 'en') ?? lookup(dicts, 'ko') ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value))
    }
  }
  return text
}

/** 에이전트가 반환한 한국어 risk_type을 화면 언어로 변환. 사전에 없으면 원문 유지. */
export function riskTypeLabel(lang: LangCode, koreanType: string): string {
  if (lang === 'ko') return koreanType
  return RISK_TYPES[lang]?.[koreanType] ?? RISK_TYPES.en[koreanType] ?? koreanType
}

export function riskLevelLabel(lang: LangCode, level: '안전' | '주의' | '위험'): string {
  const key = level === '위험' ? 'danger' : level === '주의' ? 'caution' : 'safe'
  return t(lang, key)
}
